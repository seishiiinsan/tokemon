/** @type {Map<string, Rarity>} */
const BY_ID = new Map()
for (const rarity of /** @type {Exclude<Rarity, 'common'>[]} */ (['uncommon', 'rare', 'epic', 'legendary'])) {
  for (const id of RARITY_LISTS[rarity]) BY_ID.set(id, rarity)
}

/**
 * @param {string} speciesId dossier de sprites (clé de SPECIES)
 * @returns {Rarity}
 */
export function rarityOf(speciesId) {
  const species = SPECIES[speciesId]
  if (!species) return 'common'
  return BY_ID.get(species.base) ?? BY_ID.get(species.family) ?? 'common'
}
